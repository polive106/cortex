// Embeds tailwindcss's index.css as a module, so the artifact builder never reads node_modules
// at runtime (ADR-0012). Run after upgrading tailwindcss: `pnpm sync:tailwind`.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(require.resolve("tailwindcss")), "..");
const { version } = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const css = await readFile(join(root, "index.css"), "utf8");
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/tailwind-artifact-builder/tailwind-base.generated.ts",
);
await writeFile(
  target,
  `// Generated by packages/adapters/scripts/sync-tailwind-base.mjs from tailwindcss ${version}. Don't edit.\nexport const TAILWIND_VERSION = ${JSON.stringify(version)};\nexport const TAILWIND_BASE_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`Embedded tailwindcss ${version} index.css (${css.length} chars)`);
